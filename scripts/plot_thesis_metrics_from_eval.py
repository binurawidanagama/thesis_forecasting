def plot_overall_metric_bars(df: pd.DataFrame, out_dir: Path, formats: Sequence[str]) -> List[str]:
    created = []
    for task, lookback, horizon in grouped_runs(df):
        sub = subset_run(df, task, lookback, horizon)
        if sub.empty:
            continue
        target_count = int(sub.get("target", pd.Series(dtype=object)).nunique()) if "target" in sub.columns else None
        sub = sub.sort_values(["model_label"]).copy()
        order = order_models(sub["model_label"].tolist())
        sub["model_label"] = pd.Categorical(sub["model_label"], categories=order, ordered=True)
        sub = sub.sort_values("model_label")

        for metric in METRICS:
            if metric not in sub.columns:
                continue
            fig, ax = plt.subplots(figsize=(10.5, 6.2))
            labels = sub["model_label"].astype(str).tolist()
            values = sub[metric].to_numpy(dtype=float)
            colors = [MODEL_COLORS.get(lbl, MODEL_COLORS["UNKNOWN"]) for lbl in labels]
            bars = ax.bar(labels, values, color=colors, edgecolor="black", linewidth=0.6)
            annotate_bars(ax, bars, fmt="{:.3f}" if metric != "sMAPE" else "{:.2f}")
            if np.isfinite(values).any():
                best_idx = int(np.nanargmin(values))
                ax.text(best_idx, values[best_idx], "\nBest", ha="center", va="bottom", fontsize=10, fontweight="bold")
            ax.set_ylabel(METRIC_LABELS.get(metric, metric))
            ax.set_xlabel("Model")
            ax.set_title(f"{task}: Overall {metric} comparison\nLookback = {lookback}, Forecast horizon = {horizon} steps")
            ax.set_axisbelow(True)
            expl = METRIC_EXPLANATIONS[metric]
            add_footnote(
                fig,
                [
                    expl,
                    "Shorter bars mean predictions stayed closer to the true observed values.",
                    *note_for_task(task),
                ],
            )
            fig.tight_layout(rect=[0, 0.08, 1, 1])
            base = out_dir / "overall" / safe_name(f"overall_{task}_LB{lookback}_H{horizon}_{metric}")
            save_figure(fig, base, formats)
            created.append(str(base.with_suffix(f".{formats[0]}")))
    return created


def plot_horizon_lines(df: pd.DataFrame, out_dir: Path, formats: Sequence[str]) -> List[str]:
    created = []
    if df.empty or "horizon_step" not in df.columns:
        return created

    for task, lookback, horizon in grouped_runs(df):
        sub = subset_run(df, task, lookback, horizon)
        if sub.empty:
            continue
        order = order_models(sub["model_label"].tolist())
        for metric in METRICS:
            if metric not in sub.columns:
                continue
            fig, ax = plt.subplots(figsize=(10.8, 6.2))
            for model in order:
                g = sub[sub["model_label"] == model].sort_values("horizon_step")
                if g.empty:
                    continue
                ax.plot(
                    g["horizon_step"],
                    g[metric],
                    marker="o",
                    linewidth=2.2,
                    markersize=5,
                    label=model,
                    color=MODEL_COLORS.get(model, MODEL_COLORS["UNKNOWN"]),
                )
                last = g.iloc[-1]
                if np.isfinite(last[metric]):
                    ax.text(last["horizon_step"] + 0.15, last[metric], model, fontsize=9, va="center")
            ax.set_title(f"{task}: {metric} as the forecast looks further ahead\nLookback = {lookback}, Forecast horizon = {horizon} steps")
            ax.set_xlabel("Forecast step ahead (1 = nearest future, larger = further future)")
            ax.set_ylabel(METRIC_LABELS.get(metric, metric))
            ax.legend(loc="best", frameon=True)
            add_footnote(
                fig,
                [
                    METRIC_EXPLANATIONS[metric],
                    "A flatter line means the model keeps its error more stable as the prediction goes further into the future.",
                    *note_for_task(task),
                ],
            )
            fig.tight_layout(rect=[0, 0.08, 1, 1])
            base = out_dir / "by_horizon" / safe_name(f"by_horizon_{task}_LB{lookback}_H{horizon}_{metric}")
            save_figure(fig, base, formats)
            created.append(str(base.with_suffix(f".{formats[0]}")))
    return created


def plot_target_grouped_bars(df: pd.DataFrame, out_dir: Path, formats: Sequence[str]) -> List[str]:
    created = []
    if df.empty or "target_label" not in df.columns:
        return created

    for task, lookback, horizon in grouped_runs(df):
        sub = subset_run(df, task, lookback, horizon)
        if sub.empty:
            continue
        targets = list(sub["target_label"].dropna().drop_duplicates())
        models = order_models(sub["model_label"].tolist())
        x = np.arange(len(targets))
        n_models = max(len(models), 1)
        width = min(0.8 / n_models, 0.22)

        for metric in METRICS:
            if metric not in sub.columns:
                continue
            fig, ax = plt.subplots(figsize=(max(10.5, 1.8 * len(targets) + 4), 6.4))
            for idx, model in enumerate(models):
                g = sub[sub["model_label"] == model].copy()
                vals = []
                for t in targets:
                    rows = g[g["target_label"] == t]
                    vals.append(float(rows[metric].iloc[0]) if not rows.empty else np.nan)
                offset = (idx - (n_models - 1) / 2) * width
                bars = ax.bar(
                    x + offset,
                    vals,
                    width=width,
                    label=model,
                    color=MODEL_COLORS.get(model, MODEL_COLORS["UNKNOWN"]),
                    edgecolor="black",
                    linewidth=0.5,
                )
                annotate_bars(ax, bars, fmt="{:.3f}" if metric != "sMAPE" else "{:.2f}")

            ax.set_xticks(x)
            ax.set_xticklabels(targets, rotation=20, ha="right")
            ax.set_ylabel(METRIC_LABELS.get(metric, metric))
            ax.set_xlabel("Target variable")
            ax.set_title(f"{task}: {metric} for each target variable\nLookback = {lookback}, Forecast horizon = {horizon} steps")
            ax.legend(ncol=min(4, len(models)), loc="best", frameon=True)
            add_footnote(
                fig,
                [
                    METRIC_EXPLANATIONS[metric],
                    "Within each target, the shortest bar marks the most accurate model.",
                ],
            )
            fig.tight_layout(rect=[0, 0.08, 1, 1])
            base = out_dir / "by_target" / safe_name(f"by_target_{task}_LB{lookback}_H{horizon}_{metric}")
            save_figure(fig, base, formats)
            created.append(str(base.with_suffix(f".{formats[0]}")))
    return created


def plot_target_horizon_heatmaps(df: pd.DataFrame, out_dir: Path, formats: Sequence[str]) -> List[str]:
    created = []
    if df.empty or not {"target_label", "horizon_step"}.issubset(df.columns):
        return created

    for task, lookback, horizon in grouped_runs(df):
        sub = subset_run(df, task, lookback, horizon)
        if sub.empty:
            continue
        targets = list(sub["target_label"].dropna().drop_duplicates())
        steps = sorted(pd.to_numeric(sub["horizon_step"], errors="coerce").dropna().astype(int).unique().tolist())
        models = order_models(sub["model_label"].tolist())
        n_models = len(models)
        if n_models == 0 or not targets or not steps:
            continue

        ncols = 2 if n_models > 1 else 1
        nrows = math.ceil(n_models / ncols)

        for metric in METRICS:
            if metric not in sub.columns:
                continue

            all_vals = pd.to_numeric(sub[metric], errors="coerce").to_numpy(dtype=float)
            finite = all_vals[np.isfinite(all_vals)]
            if finite.size == 0:
                continue
            vmin, vmax = float(np.nanmin(finite)), float(np.nanmax(finite))

            fig, axes = plt.subplots(nrows, ncols, figsize=(6.2 * ncols, 3.0 * nrows + 2.0), squeeze=False)
            axes_flat = axes.flatten()

            im = None
            for ax, model in zip(axes_flat, models):
                g = sub[sub["model_label"] == model]
                mat = np.full((len(targets), len(steps)), np.nan, dtype=float)
                for i, target in enumerate(targets):
                    for j, step in enumerate(steps):
                        rows = g[(g["target_label"] == target) & (g["horizon_step"].astype(int) == int(step))]
                        if not rows.empty:
                            mat[i, j] = float(rows[metric].iloc[0])
                im = ax.imshow(mat, aspect="auto", interpolation="nearest", vmin=vmin, vmax=vmax)
                ax.set_title(model)
                ax.set_xticks(np.arange(len(steps)))
                ax.set_xticklabels(steps)
                ax.set_yticks(np.arange(len(targets)))
                ax.set_yticklabels(targets)
                ax.set_xlabel("Forecast step ahead")
                ax.set_ylabel("Target")
                for i in range(len(targets)):
                    for j in range(len(steps)):
                        val = mat[i, j]
                        if np.isfinite(val):
                            text_color = "white" if val > (vmin + vmax) / 2 else "black"
                            ax.text(j, i, f"{val:.2f}", ha="center", va="center", fontsize=8, color=text_color)

            for ax in axes_flat[n_models:]:
                ax.axis("off")

            if im is not None:
                cbar = fig.colorbar(im, ax=axes_flat[:n_models], shrink=0.92)
                cbar.set_label(METRIC_LABELS.get(metric, metric))

            fig.suptitle(f"{task}: {metric} heatmaps by target and forecast step\nLookback = {lookback}, Forecast horizon = {horizon} steps", fontsize=14)
            add_footnote(
                fig,
                [
                    METRIC_EXPLANATIONS[metric],
                    "Each cell compares a model against the true values for one target and one forecast step. Darker or more intense regions correspond to larger error values on the shared color scale.",
                ],
            )
            fig.subplots_adjust(left=0.08, right=0.92, bottom=0.13, top=0.86, wspace=0.28, hspace=0.38)
            base = out_dir / "heatmaps" / safe_name(f"heatmap_{task}_LB{lookback}_H{horizon}_{metric}")
            save_figure(fig, base, formats)
            created.append(str(base.with_suffix(f".{formats[0]}")))
    return created


def plot_persistence_ratio_bars(df: pd.DataFrame, out_dir: Path, formats: Sequence[str]) -> List[str]:
    created = []
    if df.empty or "RMSE_ratio" not in df.columns:
        return created

    for task, lookback, horizon in grouped_runs(df):
        sub = subset_run(df, task, lookback, horizon)
        if sub.empty:
            continue
        sub = sub.sort_values("RMSE_ratio").copy()
        labels = sub["model_label"].astype(str).tolist()
        values = sub["RMSE_ratio"].to_numpy(dtype=float)
        colors = [MODEL_COLORS.get(lbl, MODEL_COLORS["UNKNOWN"]) for lbl in labels]

        fig, ax = plt.subplots(figsize=(10.5, 6.1))
        bars = ax.bar(labels, values, color=colors, edgecolor="black", linewidth=0.6)
        annotate_bars(ax, bars, fmt="{:.3f}")
        ax.axhline(1.0, color="black", linestyle="--", linewidth=1.2)
        ax.text(len(labels) - 0.5, 1.0, "  Persistence baseline = 1.0", va="bottom", ha="right", fontsize=10)
        if np.isfinite(values).any():
            best_idx = int(np.nanargmin(values))
            ax.text(best_idx, values[best_idx], "\nBest", ha="center", va="bottom", fontsize=10, fontweight="bold")
        ax.set_ylabel(METRIC_LABELS["RMSE_ratio"])
        ax.set_xlabel("Model")
        ax.set_title(f"{task}: RMSE ratio against persistence baseline\nLookback = {lookback}, Forecast horizon = {horizon} steps")
        add_footnote(
            fig,
            [
                METRIC_EXPLANATIONS["RMSE_ratio"],
                "Bars below the dashed line beat the persistence baseline. Bars above the line perform worse than simply repeating the last observed value.",
                *note_for_task(task),
            ],
        )
        fig.tight_layout(rect=[0, 0.08, 1, 1])
        base = out_dir / "ratios" / safe_name(f"rmse_ratio_{task}_LB{lookback}_H{horizon}")
        save_figure(fig, base, formats)
        created.append(str(base.with_suffix(f".{formats[0]}")))

        if "RMSE_gain" in sub.columns:
            fig, ax = plt.subplots(figsize=(10.5, 6.1))
            gain_vals = sub["RMSE_gain"].to_numpy(dtype=float)
            bars = ax.bar(labels, gain_vals, color=colors, edgecolor="black", linewidth=0.6)
            annotate_bars(ax, bars, fmt="{:.3f}")
            ax.axhline(0.0, color="black", linestyle="--", linewidth=1.2)
            ax.set_ylabel(METRIC_LABELS["RMSE_gain"])
            ax.set_xlabel("Model")
            ax.set_title(f"{task}: RMSE gain over persistence baseline\nLookback = {lookback}, Forecast horizon = {horizon} steps")
            add_footnote(
                fig,
                [
                    METRIC_EXPLANATIONS["RMSE_gain"],
                    "Bars above zero improve on the persistence baseline. Negative bars mean the model underperformed that baseline.",
                    *note_for_task(task),
                ],
            )
            fig.tight_layout(rect=[0, 0.08, 1, 1])
            base = out_dir / "ratios" / safe_name(f"rmse_gain_{task}_LB{lookback}_H{horizon}")
            save_figure(fig, base, formats)
            created.append(str(base.with_suffix(f".{formats[0]}")))

    return created


def plot_rmse_dashboard(
    overall_df: pd.DataFrame,
    by_horizon_df: pd.DataFrame,
    by_target_df: pd.DataFrame,
    ratio_df: pd.DataFrame,
    out_dir: Path,
    formats: Sequence[str],
) -> List[str]:
    created = []
    for task, lookback, horizon in grouped_runs(overall_df):
        o = subset_run(overall_df, task, lookback, horizon)
        h = subset_run(by_horizon_df, task, lookback, horizon)
        t = subset_run(by_target_df, task, lookback, horizon)
        r = subset_run(ratio_df, task, lookback, horizon) if not ratio_df.empty else pd.DataFrame()
        if o.empty:
            continue

        fig, axes = plt.subplots(2, 2, figsize=(14, 10))
        ax1, ax2, ax3, ax4 = axes.flatten()

        # Panel 1: overall RMSE
        o = o.sort_values("RMSE")
        labels = o["model_label"].astype(str).tolist()
        vals = o["RMSE"].to_numpy(dtype=float)
        colors = [MODEL_COLORS.get(lbl, MODEL_COLORS["UNKNOWN"]) for lbl in labels]
        bars = ax1.bar(labels, vals, color=colors, edgecolor="black", linewidth=0.6)
        annotate_bars(ax1, bars, fmt="{:.3f}")
        ax1.set_title("Overall RMSE by model")
        ax1.set_ylabel("RMSE")
        ax1.set_xlabel("Model")

        # Panel 2: horizon RMSE
        for model in order_models(h["model_label"].tolist() if not h.empty else []):
            g = h[h["model_label"] == model].sort_values("horizon_step")
            if g.empty:
                continue
            ax2.plot(
                g["horizon_step"], g["RMSE"], marker="o", linewidth=2, label=model,
                color=MODEL_COLORS.get(model, MODEL_COLORS["UNKNOWN"])
            )
        ax2.set_title("RMSE as forecast goes further ahead")
        ax2.set_xlabel("Forecast step ahead")
        ax2.set_ylabel("RMSE")
        if not h.empty:
            ax2.legend(loc="best", frameon=True)

        # Panel 3: target RMSE
        if not t.empty and "target_label" in t.columns:
            targets = list(t["target_label"].dropna().drop_duplicates())
            models = order_models(t["model_label"].tolist())
            x = np.arange(len(targets))
            width = min(0.8 / max(len(models), 1), 0.22)
            for idx, model in enumerate(models):
                g = t[t["model_label"] == model]
                vals = []
                for target in targets:
                    rows = g[g["target_label"] == target]
                    vals.append(float(rows["RMSE"].iloc[0]) if not rows.empty else np.nan)
                offset = (idx - (len(models) - 1) / 2) * width
                ax3.bar(
                    x + offset,
                    vals,
                    width=width,
                    label=model,
                    color=MODEL_COLORS.get(model, MODEL_COLORS["UNKNOWN"]),
                    edgecolor="black",
                    linewidth=0.5,
                )
            ax3.set_xticks(x)
            ax3.set_xticklabels(targets, rotation=20, ha="right")
            ax3.set_title("RMSE by target")
            ax3.set_xlabel("Target")
            ax3.set_ylabel("RMSE")
        else:
            ax3.axis("off")
            ax3.text(0.5, 0.5, "Per-target RMSE not available", ha="center", va="center", fontsize=12)

        # Panel 4: ratio or text panel
        if not r.empty and "RMSE_ratio" in r.columns:
            r = r.sort_values("RMSE_ratio")
            labels = r["model_label"].astype(str).tolist()
            vals = r["RMSE_ratio"].to_numpy(dtype=float)
            colors = [MODEL_COLORS.get(lbl, MODEL_COLORS["UNKNOWN"]) for lbl in labels]
            ax4.bar(labels, vals, color=colors, edgecolor="black", linewidth=0.6)
            ax4.axhline(1.0, color="black", linestyle="--", linewidth=1.2)
            ax4.set_title("RMSE ratio vs persistence baseline")
            ax4.set_xlabel("Model")
            ax4.set_ylabel("RMSE ratio")
        else:
            ax4.axis("off")
            ax4.text(
                0.5,
                0.6,
                "Persistence ratio plot not available.\nThis happens when summary CSV files were not found.",
                ha="center",
                va="center",
                fontsize=12,
            )

        fig.suptitle(
            f"Results dashboard: {task} | Lookback = {lookback} | Forecast horizon = {horizon} steps",
            fontsize=16,
            fontweight="bold",
        )
        add_footnote(
            fig,
            [
                "Reading guide: shorter bars and lower lines mean better accuracy. The dashboard is designed as a quick visual summary for thesis chapters and presentations.",
                *note_for_task(task),
            ],
        )
        fig.tight_layout(rect=[0, 0.08, 1, 0.95])
        base = out_dir / "dashboards" / safe_name(f"dashboard_rmse_{task}_LB{lookback}_H{horizon}")
        save_figure(fig, base, formats)
        created.append(str(base.with_suffix(f".{formats[0]}")))
    return created


