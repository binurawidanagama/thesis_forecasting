METRICS = ["RMSE", "MAE", "sMAPE"]
MODEL_ORDER = ["CNN", "LSTM", "dCeNN+ELM", "dCeNN+ELM+ASP"]
MODEL_COLORS = {
    "CNN": "#4E79A7",
    "LSTM": "#F28E2B",
    "dCeNN+ELM": "#59A14F",
    "dCeNN+ELM+ASP": "#E15759",
    "UNKNOWN": "#9C9C9C",
}

METRIC_LABELS = {
    "RMSE": "RMSE",
    "MAE": "MAE",
    "sMAPE": "sMAPE (%)",
    "RMSE_ratio": "RMSE / Persistence RMSE",
    "RMSE_gain": "RMSE gain over persistence",
}

METRIC_EXPLANATIONS = {
    "RMSE": "Lower is better. This metric punishes large mistakes more strongly than MAE.",
    "MAE": "Lower is better. This is the average absolute distance between prediction and truth.",
    "sMAPE": "Lower is better. This is a percentage-style error that is easier to compare across scales.",
    "RMSE_ratio": "Lower is better. Values below 1.0 mean the model beats the persistence baseline.",
    "RMSE_gain": "Higher is better. Positive values mean improvement over the persistence baseline.",
}

TARGET_NAME_MAP = {
    "load_mw": "Load",
    "temperature_2m_c": "Temperature",
    "mean_global_radiation": "Global radiation",
    "precipitation_mm": "Precipitation",
    "mean_wind_speed": "Wind speed",
}


def ensure_dir(path: Path) -> None:
    path.mkdir(parents=True, exist_ok=True)


def safe_name(text: str) -> str:
    out = "".join(ch if ch.isalnum() or ch in "-_" else "_" for ch in str(text))
    while "__" in out:
        out = out.replace("__", "_")
    return out.strip("_") or "figure"


def pretty_target(name: str) -> str:
    key = str(name).strip().lower()
    return TARGET_NAME_MAP.get(key, str(name).replace("_", " ").replace("/", " ").title())


def model_display(row: pd.Series) -> str:
    model = str(row.get("model", "UNKNOWN"))
    variant = str(row.get("variant", ""))
    if model in {"CNN", "LSTM", "dCeNN+ELM", "dCeNN+ELM+ASP"}:
        return model
    if variant and variant.lower() not in {"", "baseline", "raw", "asp"}:
        return f"{model} ({variant})"
    return model


def order_models(labels: Iterable[str]) -> List[str]:
    labels = list(dict.fromkeys(labels))
    known = [m for m in MODEL_ORDER if m in labels]
    unknown = sorted([m for m in labels if m not in known])
    return known + unknown


def wrap_text(text: str, width: int = 105) -> str:
    return "\n".join(textwrap.wrap(text, width=width))


def load_csv(path: Path) -> pd.DataFrame:
    if not path.exists():
        return pd.DataFrame()
    return pd.read_csv(path)


def prepare_df(df: pd.DataFrame) -> pd.DataFrame:
    if df.empty:
        return df.copy()
    out = df.copy()
    if "task" in out.columns:
        out["task"] = out["task"].astype(str).str.upper()
    if "target" in out.columns:
        out["target_label"] = out["target"].map(pretty_target)
    out["model_label"] = out.apply(model_display, axis=1)
    for c in ["lookback", "horizon", "horizon_step", "RMSE", "MAE", "sMAPE", "RMSE_ratio", "RMSE_gain"]:
        if c in out.columns:
            out[c] = pd.to_numeric(out[c], errors="coerce")
    return out


def grouped_runs(df: pd.DataFrame) -> List[Tuple[str, int, int]]:
    if df.empty:
        return []
    keys = df[["task", "lookback", "horizon"]].drop_duplicates().sort_values(["task", "lookback", "horizon"])
    return [(str(r.task), int(r.lookback), int(r.horizon)) for r in keys.itertuples(index=False)]


def subset_run(df: pd.DataFrame, task: str, lookback: int, horizon: int) -> pd.DataFrame:
    if df.empty:
        return df.copy()
    mask = (
        (df["task"].astype(str) == str(task))
        & (df["lookback"].astype(int) == int(lookback))
        & (df["horizon"].astype(int) == int(horizon))
    )
    return df.loc[mask].copy()


def save_figure(fig: plt.Figure, base_path: Path, formats: Sequence[str]) -> None:
    ensure_dir(base_path.parent)
    for ext in formats:
        fig.savefig(base_path.with_suffix(f".{ext}"), bbox_inches="tight")
    plt.close(fig)


def add_footnote(fig: plt.Figure, lines: List[str]) -> None:
    text = "\n".join([wrap_text(line, 125) for line in lines if line])
    fig.text(0.01, 0.01, text, ha="left", va="bottom", fontsize=9, color="#404040")


def annotate_bars(ax: plt.Axes, bars, fmt: str = "{:.3f}") -> None:
    values = [bar.get_height() for bar in bars]
    finite_vals = [v for v in values if np.isfinite(v)]
    ymax = max(finite_vals) if finite_vals else 1.0
    for bar in bars:
        h = bar.get_height()
        if not np.isfinite(h):
            continue
        ax.text(
            bar.get_x() + bar.get_width() / 2,
            h + ymax * 0.015,
            fmt.format(h),
            ha="center",
            va="bottom",
            fontsize=9,
            rotation=0,
        )


def note_for_task(task: str, target_count: Optional[int] = None) -> List[str]:
    notes = []
    if str(task).upper() == "WEATHER":
        notes.append(
            "Weather is multi-target. Aggregate RMSE/MAE combine different physical variables, so these plots are best used to compare models within WEATHER rather than to interpret absolute physical units."
        )
    if target_count is not None and target_count > 1:
        notes.append(f"This run contains {target_count} targets. Per-target plots and heatmaps are the most interpretable view.")
    return notes


