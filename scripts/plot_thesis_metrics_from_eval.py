def write_plot_readme(out_dir: Path, counts: Dict[str, int]) -> None:
    lines = [
        "Thesis Plot Pack",
        "================",
        "",
        "This folder contains publication-style figures generated from evaluate_all_from_parquets.py outputs.",
        "",
        "Folders:",
        "- dashboards : one compact RMSE summary figure per task/lookback/horizon",
        "- overall    : overall model comparison bar charts",
        "- by_horizon : how error changes as the forecast goes further into the future",
        "- by_target  : model comparison for each target variable",
        "- heatmaps   : target × forecast-step error maps for each model",
        "- ratios     : persistence-baseline comparison plots (when summary CSVs exist)",
        "",
        "Interpretation rules:",
        "- Lower RMSE, MAE, and sMAPE are better.",
        "- RMSE_ratio below 1.0 means the model beats the persistence baseline.",
        "- RMSE_gain above 0.0 means the model improves over the persistence baseline.",
        "",
        "Files created:",
    ]
    for name, count in counts.items():
        lines.append(f"- {name}: {count}")
    (out_dir / "PLOT_README.txt").write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    ap = argparse.ArgumentParser(description="Create thesis-grade plots from parquet evaluation CSV files.")
    ap.add_argument("--eval_dir", type=str, default="parquet_eval", help="Directory created by evaluate_all_from_parquets.py")
    ap.add_argument("--out_dir", type=str, default="thesis_plots", help="Directory where figures will be written")
    ap.add_argument("--formats", nargs="+", default=["png", "svg"], help="Output figure formats, e.g. png svg pdf")
    ap.add_argument("--dpi", type=int, default=300, help="Save DPI for raster formats")
    args = ap.parse_args()

    plt.rcParams["savefig.dpi"] = int(args.dpi)

    eval_dir = Path(args.eval_dir)
    out_dir = Path(args.out_dir)
    ensure_dir(out_dir)

    overall = prepare_df(load_csv(eval_dir / "metrics_overall_from_parquets.csv"))
    by_target = prepare_df(load_csv(eval_dir / "metrics_by_target_from_parquets.csv"))
    by_horizon = prepare_df(load_csv(eval_dir / "metrics_by_horizon_step_from_parquets.csv"))
    by_target_horizon = prepare_df(load_csv(eval_dir / "metrics_by_target_horizon_from_parquets.csv"))
    summary = prepare_df(load_csv(eval_dir / "summary_overall_with_persistence_ratios.csv"))

    if overall.empty and by_target.empty and by_horizon.empty and by_target_horizon.empty:
        raise FileNotFoundError(
            f"No evaluation CSV files were found in {eval_dir}. Run evaluate_all_from_parquets.py first."
        )

    counts: Dict[str, int] = {}
    counts["dashboards"] = len(plot_rmse_dashboard(overall, by_horizon, by_target, summary, out_dir, args.formats))
    counts["overall"] = len(plot_overall_metric_bars(overall, out_dir, args.formats))
    counts["by_horizon"] = len(plot_horizon_lines(by_horizon, out_dir, args.formats))
    counts["by_target"] = len(plot_target_grouped_bars(by_target, out_dir, args.formats))
    counts["heatmaps"] = len(plot_target_horizon_heatmaps(by_target_horizon, out_dir, args.formats))
    counts["ratios"] = len(plot_persistence_ratio_bars(summary, out_dir, args.formats))
    write_plot_readme(out_dir, counts)

    print("\n[OK] Thesis-grade plots saved to:", out_dir)
    for name, count in counts.items():
        print(f"  - {name}: {count} figure(s)")
    print("  - PLOT_README.txt")


if __name__ == "__main__":
    main()
