#!/usr/bin/env python3
"""
Create thesis-grade plots from CSV outputs generated by evaluate_all_from_parquets.py.

Reads:
  - metrics_overall_from_parquets.csv
  - metrics_by_target_from_parquets.csv
  - metrics_by_horizon_step_from_parquets.csv
  - metrics_by_target_horizon_from_parquets.csv
  - summary_overall_with_persistence_ratios.csv   (optional)

Outputs a clean set of figures for thesis chapters / results sections:
  1) Overall model comparison bar charts (RMSE, MAE, sMAPE)
  2) Error vs forecast-step line plots
  3) Per-target grouped bar charts
  4) Target × horizon heatmaps for each model
  5) Persistence-baseline ratio plots (if summary CSV exists)
  6) One compact RMSE dashboard per task/lookback/horizon

Design goals:
  - readable for non-technical readers
  - publication-friendly sizes and DPI
  - explicit annotations: lower is better, what each metric means
  - safe handling of missing files / partial outputs

Usage:
  python scripts/plot_thesis_metrics_from_eval.py
  python scripts/plot_thesis_metrics_from_eval.py --eval_dir parquet_eval --out_dir thesis_plots
  python scripts/plot_thesis_metrics_from_eval.py --formats png svg --dpi 300
"""

